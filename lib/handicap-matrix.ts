import { opponentsAllowed, startScore, type Lineup } from './handicap'

/** One kind of player: gender and level (B, Upper C, C, D). */
export interface PlayerType {
  gender: 'M' | 'F'
  level: 'B' | 'U' | 'C' | 'D'
}
const LEVELS = ['B', 'U', 'C', 'D'] as const
export const PLAYER_TYPES: PlayerType[] = (['M', 'F'] as const).flatMap((gender) => LEVELS.map((level) => ({ gender, level })))

export const toLineup = (p: PlayerType): Lineup => ({ gender: p.gender, grade: p.level === 'B' ? 2 : p.level === 'D' ? 4 : 3, upper: p.level === 'U' })
export const typeLabel = (p: PlayerType) => `${p.gender}-${p.level}`
const sideType = (s: [PlayerType, PlayerType]) => {
  const men = s.filter((p) => p.gender === 'M').length
  return men === 2 ? 'MD' : men === 1 ? 'XD' : 'WD'
}

export interface MatrixRow {
  a: [PlayerType, PlayerType]
  b: [PlayerType, PlayerType]
  category: string
  /** null when the match is prohibited. */
  start: { a: number; b: number } | null
}

/** Every pair of teams (each team any two player types), once each: 36 teams, 666 match-ups. */
export function handicapMatrix(): MatrixRow[] {
  const teams: [PlayerType, PlayerType][] = []
  PLAYER_TYPES.forEach((x, i) => PLAYER_TYPES.slice(i).forEach((y) => teams.push([x, y])))
  const rows: MatrixRow[] = []
  teams.forEach((a, i) =>
    teams.slice(i).forEach((b) => {
      const la = a.map(toLineup) as [Lineup, Lineup]
      const lb = b.map(toLineup) as [Lineup, Lineup]
      const s = startScore(la, lb)
      rows.push({ a, b, category: `${sideType(a)} vs ${sideType(b)}`, start: opponentsAllowed(la, lb) ? { a: s.a, b: s.b } : null })
    }),
  )
  return rows
}

/** The matrix as a Markdown page (docs/handicap-matrix.md). */
export function handicapMatrixMarkdown(): string {
  const rows = handicapMatrix()
  const allowed = rows.filter((r) => r.start)
  const lines = [
    '# Handicap matrix',
    '',
    'Generated by `npx tsx scripts/handicap-matrix.ts` from `lib/handicap.ts`; a unit test checks it is up to date.',
    '',
    'M = man, F = woman; B, U = Upper C, C, D. Strength: men B 14, U 8, C 6, D 4; women B 6, U 3, C 2, D 1.',
    'Start = ceil(|team A - team B| / 2) for the weaker team. Prohibited: players more than one grade apart (B with D),',
    'or two C players with at least one Upper C against two D players.',
    '',
    `${rows.length} match-ups: ${allowed.length} allowed, ${rows.length - allowed.length} prohibited.`,
    '',
    '| Team A | Team B | Type | Start A : B |',
    '|---|---|---|---|',
    ...rows.map((r) => `| ${r.a.map(typeLabel).join(' + ')} | ${r.b.map(typeLabel).join(' + ')} | ${r.category} | ${r.start ? `${r.start.a} : ${r.start.b}` : 'Prohibited'} |`),
    '',
  ]
  return lines.join('\n')
}
