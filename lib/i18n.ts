export type Lang = 'en' | 'zh'
export type T = (k: Key) => string

export function getLang(): Lang {
  return cookies().get('lang')?.value === 'zh' ? 'zh' : 'en'
}

export function getT(): { t: T; lang: Lang } {
  const lang = getLang()
  const dict = lang === 'zh' ? zh : en
  return { t: (k) => dict[k], lang }
}
